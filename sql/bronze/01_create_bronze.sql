
-- Chicago 311 Service Intelligence
-- Development environment: Bronze layer

CREATE DATABASE IF NOT EXISTS CHICAGO_311_DEV;

CREATE SCHEMA IF NOT EXISTS CHICAGO_311_DEV.BRONZE;

-- JSON Lines (one JSON object per line)
CREATE FILE FORMAT IF NOT EXISTS
    CHICAGO_311_DEV.BRONZE.JSONL_FORMAT
    TYPE = JSON
    COMPRESSION = AUTO
    STRIP_OUTER_ARRAY = FALSE;

-- Append-only landing table for source records.
CREATE TABLE IF NOT EXISTS
    CHICAGO_311_DEV.BRONZE.SERVICE_REQUEST_RAW
(
    RAW_RECORD VARIANT NOT NULL,
    SOURCE_FILE VARCHAR(1024),
    SOURCE_ROW_NUMBER NUMBER(38, 0),
    INGESTED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP()
);
