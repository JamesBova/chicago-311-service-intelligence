
-- Chicago 311 Service Intelligence
-- Automatically ingest new S3 files into Bronze.

USE ROLE ACCOUNTADMIN;

CREATE PIPE IF NOT EXISTS CHICAGO_311_DEV.BRONZE.CHICAGO_311_PIPE
    AUTO_INGEST = TRUE
AS
COPY INTO CHICAGO_311_DEV.BRONZE.SERVICE_REQUEST_RAW
    (
        RAW_RECORD,
        SOURCE_FILE,
        SOURCE_ROW_NUMBER
    )
FROM (
    SELECT
        $1,
        METADATA$FILENAME,
        METADATA$FILE_ROW_NUMBER
    FROM @CHICAGO_311_DEV.BRONZE.S3_CHICAGO_311_STAGE
);

-- Retrieve the SQS notification channel.
DESC PIPE CHICAGO_311_DEV.BRONZE.CHICAGO_311_PIPE;
