
USE ROLE SECURITYADMIN;

-- Create the transformation role
CREATE ROLE IF NOT EXISTS CHICAGO_311_TRANSFORM_ROLE;

-- Create the dedicated Airflow service account
CREATE USER IF NOT EXISTS CHICAGO_311_AIRFLOW_SVC
    TYPE = SERVICE
    DEFAULT_ROLE = CHICAGO_311_TRANSFORM_ROLE
    DEFAULT_SECONDARY_ROLES = ()
    COMMENT = 'Service account for Chicago 311 Airflow processing';

-- Assign the role to the service account
GRANT ROLE CHICAGO_311_TRANSFORM_ROLE
    TO USER CHICAGO_311_AIRFLOW_SVC;


USE ROLE SECURITYADMIN;

GRANT USAGE ON DATABASE CHICAGO_311_DEV
    TO ROLE CHICAGO_311_TRANSFORM_ROLE;

GRANT USAGE ON WAREHOUSE DE_PORTFOLIO_WH
    TO ROLE CHICAGO_311_TRANSFORM_ROLE;




USE ROLE SECURITYADMIN;

-- BRONZE: Read-only
GRANT USAGE ON SCHEMA CHICAGO_311_DEV.BRONZE
    TO ROLE CHICAGO_311_TRANSFORM_ROLE;

GRANT SELECT ON ALL TABLES IN SCHEMA CHICAGO_311_DEV.BRONZE
    TO ROLE CHICAGO_311_TRANSFORM_ROLE;

GRANT SELECT ON FUTURE TABLES IN SCHEMA CHICAGO_311_DEV.BRONZE
    TO ROLE CHICAGO_311_TRANSFORM_ROLE;

GRANT SELECT ON ALL VIEWS IN SCHEMA CHICAGO_311_DEV.BRONZE
    TO ROLE CHICAGO_311_TRANSFORM_ROLE;

GRANT SELECT ON FUTURE VIEWS IN SCHEMA CHICAGO_311_DEV.BRONZE
    TO ROLE CHICAGO_311_TRANSFORM_ROLE;

-- Allow Airflow to enforce the seven-day Bronze retention policy.
GRANT DELETE
ON TABLE CHICAGO_311_DEV.BRONZE.SERVICE_REQUEST_RAW
TO ROLE CHICAGO_311_TRANSFORM_ROLE;

GRANT SELECT
ON STREAM CHICAGO_311_DEV.BRONZE.SERVICE_REQUEST_RAW_STREAM
TO ROLE CHICAGO_311_TRANSFORM_ROLE;

-- SILVER: Create transformation models
GRANT USAGE, CREATE TABLE, CREATE VIEW
    ON SCHEMA CHICAGO_311_DEV.SILVER
    TO ROLE CHICAGO_311_TRANSFORM_ROLE;

-- GOLD: Create analytical models
GRANT USAGE, CREATE TABLE, CREATE VIEW
    ON SCHEMA CHICAGO_311_DEV.GOLD
    TO ROLE CHICAGO_311_TRANSFORM_ROLE;

-- Read existing transformation tables
GRANT SELECT ON ALL TABLES IN SCHEMA CHICAGO_311_DEV.SILVER
    TO ROLE CHICAGO_311_TRANSFORM_ROLE;

GRANT SELECT ON ALL TABLES IN SCHEMA CHICAGO_311_DEV.GOLD
    TO ROLE CHICAGO_311_TRANSFORM_ROLE;

GRANT SELECT ON ALL VIEWS IN SCHEMA CHICAGO_311_DEV.SILVER
    TO ROLE CHICAGO_311_TRANSFORM_ROLE;

GRANT SELECT ON ALL VIEWS IN SCHEMA CHICAGO_311_DEV.GOLD
    TO ROLE CHICAGO_311_TRANSFORM_ROLE;




USE ROLE SECURITYADMIN;

-- Transfer existing Silver tables
GRANT OWNERSHIP ON ALL TABLES
    IN SCHEMA CHICAGO_311_DEV.SILVER
    TO ROLE CHICAGO_311_TRANSFORM_ROLE
    COPY CURRENT GRANTS;

-- Transfer existing Gold tables
GRANT OWNERSHIP ON ALL TABLES
    IN SCHEMA CHICAGO_311_DEV.GOLD
    TO ROLE CHICAGO_311_TRANSFORM_ROLE
    COPY CURRENT GRANTS;
