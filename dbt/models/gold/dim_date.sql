{{
    config(
        materialized='incremental',
        incremental_strategy='merge',
        unique_key='DATE_KEY',
        on_schema_change='fail',
        tags=['chicago-311', 'gold']
    )
}}

WITH request_dates AS (
    SELECT CAST(CREATED_DATE AS DATE) AS CALENDAR_DATE
    FROM {{ ref('service_request_current') }}
    WHERE CREATED_DATE IS NOT NULL

    UNION

    SELECT CAST(CLOSED_DATE AS DATE) AS CALENDAR_DATE
    FROM {{ ref('service_request_current') }}
    WHERE CLOSED_DATE IS NOT NULL
)

SELECT
    CAST(TO_CHAR(CALENDAR_DATE, 'YYYYMMDD') AS NUMBER(8,0))
        AS DATE_KEY,
    CALENDAR_DATE,
    CAST(YEAR(CALENDAR_DATE) AS NUMBER(4,0)) AS CALENDAR_YEAR,
    CAST(QUARTER(CALENDAR_DATE) AS NUMBER(1,0)) AS CALENDAR_QUARTER,
    CAST(MONTH(CALENDAR_DATE) AS NUMBER(2,0)) AS CALENDAR_MONTH,
    CAST(TO_CHAR(CALENDAR_DATE, 'MMMM') AS VARCHAR(20)) AS MONTH_NAME,
    CAST(WEEKISO(CALENDAR_DATE) AS NUMBER(2,0)) AS WEEK_OF_YEAR,
    CAST(DAY(CALENDAR_DATE) AS NUMBER(2,0)) AS DAY_OF_MONTH,
    CAST(DAYOFWEEKISO(CALENDAR_DATE) AS NUMBER(1,0)) AS DAY_OF_WEEK_ISO,
    CAST(TO_CHAR(CALENDAR_DATE, 'DAY') AS VARCHAR(20)) AS DAY_NAME,
    DAYOFWEEKISO(CALENDAR_DATE) IN (6, 7) AS IS_WEEKEND
FROM request_dates